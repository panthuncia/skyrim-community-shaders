	void Install()
	{
		::Testing::RegisterExitReport([] { ReportBoth("at exit"); });
		::Testing::RegisterCommand("snapshot:detect", [](const std::string&, std::string&) {
			ReportBoth("on demand");
			return true;
		});
		if (!Switches::On("CS_ENGINE_ZONES") && !Reads::Logging())
			return;
		const auto version = REL::Module::get().version();
		const bool ae = version == REL::Version(1, 6, 1170, 0);
		const bool se = version == REL::Version(1, 5, 97, 0);
		if (!ae && !se) {
			g_unsupported = "the call sites are for AE 1.6.1170 and SE 1.5.97 only";
			logger::info("[EngineZones] {}; this runtime is {}", g_unsupported, version.string());
			return;
		}
		static SKSE::Trampoline trampoline("CS engine zones");
		// Placed from the end of the engine's code (the default), so every call site in it reaches the trampoline with a rel32.
		trampoline.create(kCount * 16 + 64);
		const auto& entries = Entries();
		const auto moduleBase = REL::Module::get().base();
		const auto text = REL::Module::get().segment(REL::Segment::textx);
		const auto textBegin = text.address();
		const auto textEnd = textBegin + text.size();
		const char* runtime = ae ? "AE" : "SE";
		std::uint32_t written = 0, aeOnly = 0;
		for (std::size_t i = 0; i < kCount; ++i) {
			const auto& site = kSites[i];
			const auto parent = ae ? site.aeParent : site.seParent;
			const auto callee = ae ? site.aeCallee : site.seCallee;
			const auto offset = ae ? site.aeOffset : site.seOffset;
			if (!parent) {
				++aeOnly;
				continue;
			}
			const auto src = REL::ID(parent).address() + offset;
			if (*reinterpret_cast<const std::uint8_t*>(src) != 0xE8) {
				logger::warn("[EngineZones] {}: no CALL at {} {}+{:#x}; skipped", site.name, runtime, parent, offset);
				continue;
			}
			// The target is the engine's function, or a hook another plugin or feature wrote there first, outside the engine's code.
			const auto target = src + 5 + *reinterpret_cast<const std::int32_t*>(src + 1);
			const bool engine = target >= textBegin && target < textEnd;
			if (engine && callee && target != REL::ID(callee).address()) {
				logger::warn("[EngineZones] {}: {} {}+{:#x} calls {:#x}, not {}; skipped", site.name, runtime, parent, offset, target - moduleBase, callee);
				continue;
			}
			// The render thread may already run this site (the install runs on another thread): the thunk's target and its jump are
			// in place before the call's one atomic retarget.
			*entries[i].func = reinterpret_cast<Fn>(target);
			auto* jump = static_cast<std::uint8_t*>(trampoline.allocate(14));
			constexpr std::uint8_t kJmpAbs[6]{ 0xFF, 0x25, 0, 0, 0, 0 };  // jmp [rip+0]
			std::memcpy(jump, kJmpAbs, sizeof(kJmpAbs));
			std::memcpy(jump + sizeof(kJmpAbs), &entries[i].thunk, sizeof(entries[i].thunk));
			if (!RetargetCall(src, reinterpret_cast<std::uintptr_t>(jump))) {
				logger::warn("[EngineZones] {}: {} {}+{:#x} could not be made writable; skipped", site.name, runtime, parent, offset);
				continue;
			}
			g_hooked[i] = !engine;
			g_sources[i] = src;
			++written;
		}
		g_wrappedCount.store(written, std::memory_order_relaxed);
		g_installed.store(true, std::memory_order_release);
#ifdef TRACY_ENABLE
		constexpr const char* kTracy = ", with Tracy zones";
#else
		constexpr const char* kTracy = "";
#endif
		logger::info("[EngineZones] {} of {} engine call sites counted{}{}", written, kCount, kTracy,
			aeOnly ? fmt::format("; {} sites have no SE match, so on SE the detector covers only part of the frame (AE-only sites)", aeOnly) : std::string());
	}

	std::uintptr_t CallTarget(std::uintptr_t a_callSite)
	{
		if (g_installed.load(std::memory_order_acquire))
			for (std::size_t i = 0; i < kCount; ++i)
				if (g_sources[i] == a_callSite)
					return reinterpret_cast<std::uintptr_t>(*Entries()[i].func);
		return a_callSite + 5 + *reinterpret_cast<const std::int32_t*>(a_callSite + 1);
	}

	void BeginFrame(std::uint8_t a_kind) noexcept
	{
		// The calls since the last Begin belong to the frame that Begin started.
		const auto calls = g_frameCalls.exchange(0, std::memory_order_relaxed);
		if (g_frameBegun) {
			auto& stats = g_frameStats[g_frameKind];
			++stats.frames;
			stats.calls += calls;
			stats.max = std::max(stats.max, calls);
			stats.withCalls += calls != 0;
		}
		const bool afterLoad = g_frameBegun && g_frameKind == kLoading && a_kind == kWorld;
		g_frameKind = a_kind;
		g_frameBegun = true;
		if (afterLoad)
			Report("after a load");
	}

	void Report(const char* a_when)
	{
		const bool installed = g_installed.load(std::memory_order_acquire);
		nlohmann::json perFrame = nlohmann::json::object();
		std::string kinds;
		for (std::uint32_t k = 0; k < Reads::kKinds; ++k) {
			const auto& s = g_frameStats[k];
			if (!s.frames)
				continue;
			const double avg = static_cast<double>(s.calls) / static_cast<double>(s.frames);
			perFrame[kKindKeys[k]] = { { "frames", s.frames }, { "calls", s.calls }, { "per_frame", avg }, { "max", s.max }, { "frames_with_calls", s.withCalls } };
			kinds += fmt::format("{}{} {:.1f} per frame (max {}, {} of {} frames with any)", kinds.empty() ? "" : "; ", kKindKeys[k], avg, s.max, s.withCalls, s.frames);
		}
		nlohmann::json sites = nlohmann::json::object();
		for (std::size_t i = 0; installed && i < kCount; ++i) {
			std::uint64_t total = 0;
			for (const auto& count : g_entries[i])
				total += count.load(std::memory_order_relaxed);
			if (total)
				sites[kSites[i].name] = { { "world", g_entries[i][kWorld].load(std::memory_order_relaxed) }, { "total", total }, { "render", kSites[i].role == Role::Render } };
		}
		::Testing::SetReport("engine_render", { { "mode", RenderGraph::Frame::Driver::ModeName() }, { "installed", installed }, { "unsupported", g_unsupported },
												  { "sites_wrapped", g_wrappedCount.load(std::memory_order_relaxed) }, { "sites", kCount }, { "per_frame", perFrame },
												  { "calls", std::move(sites) } });
		if (!Reads::Logging())
			return;
		if (!installed) {
			logger::info("[EngineZones] engine render calls {}: not counted ({})", a_when, *g_unsupported ? g_unsupported : "the call sites are not installed");
			return;
		}
		const auto& world = g_frameStats[kWorld];
		logger::info("[EngineZones] engine render calls {} ({}; {} of {} sites counted): {}", a_when, RenderGraph::Frame::Driver::ModeName(),
			g_wrappedCount.load(std::memory_order_relaxed), kCount, kinds.empty() ? "no frames" : kinds);
		// The line cs-test reads.
		logger::info("[EngineZones] engine render calls per world frame: {:.1f}", world.frames ? static_cast<double>(world.calls) / static_cast<double>(world.frames) : 0.0);
		const double worldFrames = static_cast<double>(std::max<std::uint64_t>(world.frames, 1));
		for (std::size_t i = 0; i < kCount; ++i) {
			std::string split;
			std::uint64_t total = 0;
			for (std::uint32_t k = 0; k < Reads::kKinds; ++k)
				if (const auto n = g_entries[i][k].load(std::memory_order_relaxed)) {
					split += fmt::format(" {}={}", kKindKeys[k], n);
					total += n;
				}
			if (!total)
				continue;
			logger::info("[EngineZones] engine call site: {} [{}{}]: per world frame {:.2f};{}", kSites[i].name, kSites[i].role == Role::Render ? "render" : "helper",
				g_hooked[i] ? ", hooked" : "", static_cast<double>(g_entries[i][kWorld].load(std::memory_order_relaxed)) / worldFrames, split);
		}
	}
